# 1) HTTP request methods (GET, POST, PUT, DELETE):

#     GET (Retrieve Data)
#          A GET request is used when the client wants to request data from the server. The server responds with the requested data, such as a record or a list of resources, usually in a format like JSON or HTML.
        
#     POST
#         A POST request is used when the client sends data to the server to create a new resource (such as a new record). The data sent in the POST request is usually in JSON, XML, or form-encoded format.

#     PUT
#          PUT requests are used when the client wants to update an existing resource completely. The data sent in the PUT request replaces the current data.

#     DELETE
#          A DELETE request is used when the client wants to delete a resource from the server.


# 2) Sending and receiving responses in DRF:

#     in Django REST Framework (DRF), sending and receiving responses is central to building APIs that communicate effectively with clients. DRF provides various tools for handling HTTP responses and making sure data is serialized and returned in the correct format
