# 1) Understanding views in DRF: Function-based views vs Class-based views:

#     1. Function-Based Views (FBVs):
#         Function-Based Views are the simplest form of views. Each view is defined as a regular Python function that takes an HTTP request and returns an HTTP response.

#     2. Class-Based Views (CBVs)
#         Class-Based Views use Python classes to define views, and they come with predefined methods to handle different HTTP methods (GET, POST, PUT, DELETE, etc.). DRF provides a set of generic views that handle common API patterns, such as list views, detail views, create views, etc.


