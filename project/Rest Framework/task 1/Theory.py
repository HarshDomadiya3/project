#     REST
#     SOAP

# 3) Why are APIs Important in Web Development?

#     Enabling Communication Between Systems: APIs allow different software systems to communicate with each other seamlessly.

#     Integration with Third-Party Services: APIs provide a simple way for developers to integrate third-party services into their applications.

#     Faster Development: APIs allow developers to leverage existing services and data without having to reinvent the wheel. By using APIs, developers can focus on building core features of their application while relying on external APIs to handle additional functionalities, such as data retrieval or processing.