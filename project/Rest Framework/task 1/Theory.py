# 1) What is an API (Application Programming Interface)?


#     An API (Application Programming Interface) is a set of rules and protocols that allow one software application to interact with another.
# It defines how different software components should interact, 
# allowing systems to communicate with each other without needing to know the internal workings of each other.
# Essentially, APIs provide a way for programs to send and receive data and requests, 
# enabling functionality to be shared between different applications, systems, or services.

